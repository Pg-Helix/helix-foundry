#!/bin/sh
# Generates compose/.env with fresh random local credentials (never
# committed -- see .gitignore). Safe to re-run: leaves an existing .env
# alone rather than rotating credentials out from under a running stack;
# pass --force to regenerate anyway.
set -eu
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ENV_FILE="$DIR/.env"

if [ -f "$ENV_FILE" ] && [ "${1:-}" != "--force" ]; then
    echo "generate-env.sh: $ENV_FILE already exists (use --force to regenerate)" >&2
    exit 0
fi

random_password() {
    # 32 hex chars from the kernel CSPRNG -- disposable local-demo
    # credentials, not a production secret-management story.
    od -An -N24 -tx1 /dev/urandom | tr -d ' \n'
}

cat > "$ENV_FILE" <<EOF
# Generated by generate-env.sh. Local disposable demo credentials only --
# never commit this file (see .gitignore), never reuse these values
# outside a throwaway Compose stack.
HELIX_ADMIN_PASSWORD=$(random_password)
HELIX_WORKER_PASSWORD=$(random_password)
HELIX_APP_PASSWORD=$(random_password)
EOF
chmod 600 "$ENV_FILE"
echo "generate-env.sh: wrote $ENV_FILE"
